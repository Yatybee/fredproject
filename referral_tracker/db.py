# Columns added after the first release; applied to databases created earlier.
MIGRATIONS = [
    ("patients", "address", "TEXT NOT NULL DEFAULT ''"),
    ("referrals", "referring_facility", "TEXT NOT NULL DEFAULT ''"),
    ("referrals", "notes", "TEXT NOT NULL DEFAULT ''"),
]

_SCHEMA_LOCK = 727274  # arbitrary key: serialises start-up so two servers don't race on CREATE


class Row(tuple):
    """A result row readable by position, by column name, or as dict(row) (like sqlite3.Row)."""
    __slots__ = ()
    _cols = ()

    def keys(self):
        return list(self._cols)

    def __getitem__(self, key):
        if isinstance(key, str):
            return tuple.__getitem__(self, self._cols.index(key))
        return tuple.__getitem__(self, key)


def _row_factory(cursor):
    names = tuple(c.name for c in (cursor.description or ()))
    cls = type("Row", (Row,), {"__slots__": (), "_cols": names})  # one subclass per result shape
    return lambda values: cls(values)


class Connection:
    """Thin wrapper so the service layer can keep writing `?` placeholders."""

    def __init__(self, raw):
        self.raw = raw

    def execute(self, query, params=None):
        return self.raw.execute(query.replace("?", "%s"), params)

    def commit(self):
        self.raw.commit()

    def rollback(self):
        self.raw.rollback()

    def close(self):
        self.raw.close()


def _migrate(conn):
    for table, column, ddl in MIGRATIONS:
        conn.execute(f"ALTER TABLE {table} ADD COLUMN IF NOT EXISTS {column} {ddl}")


def connect(url=None, init=True, schema=None):
    """init=False skips the (idempotent) schema script, for per-request connections.

    schema: use a separate Postgres schema (the tests give each test its own).
    """
    url = url or default_url()
    if not url:
        raise RuntimeError("DATABASE_URL is not set. Use your Neon connection string.")
    raw = psycopg.connect(url, row_factory=_row_factory, connect_timeout=15)
    try:
        if schema:
            raw.execute(sql.SQL("CREATE SCHEMA IF NOT EXISTS {}").format(sql.Identifier(schema)))
            raw.execute(sql.SQL("SET search_path TO {}").format(sql.Identifier(schema)))
            raw.commit()
        conn = Connection(raw)
        if init:
            conn.execute("SELECT pg_advisory_xact_lock(?)", (_SCHEMA_LOCK,))
            raw.execute(SCHEMA)
            _migrate(conn)
            raw.commit()
    except Exception:
        raw.close()
        raise
    return conn


def make_pool(url=None, schema=None, max_size=10):
    """Reusable connections for the web server (a fresh TLS connection to Neon per request is slow).

    check=... re-tests a connection before handing it out, because Neon closes idle ones.
    """
    from psycopg_pool import ConnectionPool

    def configure(raw):
        if schema:
            raw.execute(sql.SQL("SET search_path TO {}").format(sql.Identifier(schema)))
            raw.commit()

    pool = ConnectionPool(url or default_url(), min_size=1, max_size=max_size, open=False,
                          kwargs={"row_factory": _row_factory, "connect_timeout": 15},
                          configure=configure, check=ConnectionPool.check_connection)
    pool.open()
    return pool


@contextmanager
def pooled(pool):
    """Borrow a connection from the pool as a Connection; it is rolled back and returned afterwards."""
    with pool.connection() as raw:
        yield Connection(raw)


@contextmanager
def transaction(conn):
    """Commit on success, roll back on any error, so a failure never leaves half-written data."""
    try:
        yield conn
        conn.commit()
    except Exception:
        conn.rollback()
        raise
